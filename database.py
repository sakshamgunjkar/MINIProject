from config import Config

def get_connection(dbname=None):
    """Obtain a fresh PostgreSQL connection with strict parameters."""
    raw_url = os.getenv("DATABASE_URL")
    if raw_url and not dbname:
        if raw_url.startswith("postgres://"):
            raw_url = raw_url.replace("postgres://", "postgresql://", 1)
        return psycopg2.connect(raw_url)

    return psycopg2.connect(
        host=Config.DB_HOST,
        port=Config.DB_PORT,
        user=Config.DB_USER,
        password=Config.DB_PASSWORD,
        dbname=dbname or Config.DB_NAME
    )

def ensure_database_exists():
    """Ensure smartcommute_db exists on local PostgreSQL server."""
    if os.getenv("DATABASE_URL"):
        print("[DB INIT] Cloud DATABASE_URL detected. Skipping local database creation.")
        return

    try:
        conn = psycopg2.connect(
            host=Config.DB_HOST,
            port=Config.DB_PORT,
            user=Config.DB_USER,
            password=Config.DB_PASSWORD,
            dbname="postgres"
        )
        conn.set_isolation_level(ISOLATION_LEVEL_AUTOCOMMIT)
        cur = conn.cursor()
        cur.execute("SELECT 1 FROM pg_database WHERE datname = %s", (Config.DB_NAME,))
        exists = cur.fetchone()
        if not exists:
            cur.execute(f'CREATE DATABASE "{Config.DB_NAME}";')
            print(f"[DB INIT] Created database '{Config.DB_NAME}' successfully.")
        else:
            print(f"[DB INIT] Database '{Config.DB_NAME}' verified.")
        cur.close()
        conn.close()
    except Exception as e:
        print(f"[DB ERROR] Error ensuring database exists: {e}")
        raise e

def init_tables():
    """Initialize the exact 6-table relational schema and indexes from SmartCommute_DBMS.pdf."""
    schema_sql = """
    CREATE TABLE IF NOT EXISTS users (
        user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) NOT NULL,
        email VARCHAR(150) NOT NULL UNIQUE,
        phone VARCHAR(15) UNIQUE,
        password_hash VARCHAR(255) NOT NULL,
        is_verified BOOLEAN NOT NULL DEFAULT FALSE,
        account_role VARCHAR(20) NOT NULL DEFAULT 'commuter'
            CHECK (account_role IN ('commuter', 'admin')),
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS vehicles (
        vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        owner_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
        vehicle_type VARCHAR(30) NOT NULL
            CHECK (vehicle_type IN ('car', 'bike', 'scooter', 'other')),
        capacity SMALLINT NOT NULL CHECK (capacity BETWEEN 1 AND 20),
        registration_no VARCHAR(20) NOT NULL UNIQUE,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS routes (
        route_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_by BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
        origin VARCHAR(200) NOT NULL,
        destination VARCHAR(200) NOT NULL,
        waypoints TEXT,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CHECK (origin <> destination)
    );

    CREATE TABLE IF NOT EXISTS rides (
        ride_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        driver_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
        vehicle_id BIGINT NOT NULL REFERENCES vehicles(vehicle_id) ON DELETE RESTRICT,
        route_id BIGINT NOT NULL REFERENCES routes(route_id) ON DELETE RESTRICT,
        departure_time TIMESTAMP NOT NULL,
        available_seats SMALLINT NOT NULL CHECK (available_seats >= 0),
        total_fare NUMERIC(10,2) NOT NULL CHECK (total_fare >= 0),
        ride_status VARCHAR(20) NOT NULL DEFAULT 'open'
            CHECK (ride_status IN ('open', 'full', 'in_progress', 'completed', 'cancelled')),
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS matches (
        match_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ride_id BIGINT NOT NULL REFERENCES rides(ride_id) ON DELETE CASCADE,
        passenger_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
        pickup_point VARCHAR(200) NOT NULL,
        dropoff_point VARCHAR(200) NOT NULL,
        fare_contribution NUMERIC(10,2) NOT NULL CHECK (fare_contribution >= 0),
        match_status VARCHAR(20) NOT NULL DEFAULT 'pending'
            CHECK (match_status IN ('pending', 'accepted', 'rejected', 'cancelled', 'completed')),
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CHECK (pickup_point <> dropoff_point),
        UNIQUE (ride_id, passenger_id)
    );

    CREATE TABLE IF NOT EXISTS ride_history (
        history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ride_id BIGINT NOT NULL REFERENCES rides(ride_id) ON DELETE CASCADE,
        status VARCHAR(20) NOT NULL
            CHECK (status IN ('open', 'full', 'in_progress', 'completed', 'cancelled')),
        event_note TEXT,
        recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS reviews (
        review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ride_id BIGINT REFERENCES rides(ride_id) ON DELETE SET NULL,
        reviewer_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
        driver_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
        rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
        review_text TEXT,
        tags VARCHAR(200),
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE INDEX IF NOT EXISTS idx_rides_departure_status ON rides (departure_time, ride_status);
    CREATE INDEX IF NOT EXISTS idx_rides_route_id ON rides (route_id);
    CREATE INDEX IF NOT EXISTS idx_matches_ride_status ON matches (ride_id, match_status);
    CREATE INDEX IF NOT EXISTS idx_matches_passenger ON matches (passenger_id);
    CREATE INDEX IF NOT EXISTS idx_routes_origin_destination ON routes (origin, destination);
    CREATE INDEX IF NOT EXISTS idx_reviews_driver ON reviews (driver_id);
    CREATE INDEX IF NOT EXISTS idx_reviews_rating ON reviews (rating);
    """
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute(schema_sql)
        conn.commit()
        print("[DB INIT] Tables and indexes created successfully.")
    finally:
        conn.close()

