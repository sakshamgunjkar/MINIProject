def query_db(query, args=(), one=False):
    """Execute read query and return real dict rows."""
    conn = get_connection()
    try:
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            cur.execute(query, args)
            rv = cur.fetchall()
            return (rv[0] if rv else None) if one else rv
    finally:
        conn.close()

def execute_db(query, args=(), returning_id_column=None):
    """Execute write query inside an ACID-compliant transaction."""
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute(query, args)
            returned_val = None
            if returning_id_column:
                returned_val = cur.fetchone()[0]
            conn.commit()
            return returned_val
    except Exception as e:
        conn.rollback()
        raise e
    finally:
        conn.close()

